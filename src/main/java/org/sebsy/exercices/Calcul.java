package org.sebsy.exercices;

/** Arithmétique entière. Les noms disent ce que renvoie chaque méthode : pas de Javadoc qui paraphrase. */
public class Calcul {

    public int addition(int premier, int second) {
        return premier + second;
    }

    public int soustraction(int premier, int second) {
        return premier - second;
    }
}
